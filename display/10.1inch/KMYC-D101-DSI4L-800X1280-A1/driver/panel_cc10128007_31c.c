static const char *TAG = "cc10128007_31c";

const ili9881c_lcd_init_cmd_t *cc10128007_31c_get_init_commands(size_t *command_count)
{
    if (command_count != NULL) {
        *command_count = sizeof(s_init_commands) / sizeof(s_init_commands[0]);
    }
    return s_init_commands;
}

esp_err_t cc10128007_31c_initialize(esp_lcd_panel_io_handle_t io)
{
    if (io == NULL) {
        return ESP_ERR_INVALID_ARG;
    }

    const size_t command_count = sizeof(s_init_commands) / sizeof(s_init_commands[0]);
    ESP_LOGI(TAG, "Sending %u write-only vendor commands (panel ID read skipped)",
             (unsigned)command_count);

    for (size_t i = 0; i < command_count; ++i) {
        const ili9881c_lcd_init_cmd_t *entry = &s_init_commands[i];
        esp_err_t err = esp_lcd_panel_io_tx_param(io, entry->cmd, entry->data,
                                                  entry->data_bytes);
        if (err != ESP_OK) {
            ESP_LOGE(TAG, "Command %u/%u (0x%02X) failed: %s",
                     (unsigned)(i + 1), (unsigned)command_count,
                     (unsigned)entry->cmd, esp_err_to_name(err));
            return err;
        }
        /* A zero-tick delay still yields, allowing the DSI command FIFO to drain. */
        vTaskDelay(pdMS_TO_TICKS(entry->delay_ms));
    }

    ESP_LOGI(TAG, "Vendor initialization sequence complete");
    return ESP_OK;
}

esp_err_t cc10128007_31c_enable_bist(esp_lcd_panel_io_handle_t io)
{
    if (io == NULL) {
        return ESP_ERR_INVALID_ARG;
    }

    static const uint8_t page4[] = {0x98, 0x81, 0x04};
    static const uint8_t all_patterns = 0xFF;
    static const uint8_t enable_64_frames = 0x01;
    static const uint8_t page0[] = {0x98, 0x81, 0x00};

    ESP_LOGI(TAG, "Enabling controller BIST: all patterns, 64 frames each");
    esp_err_t err = esp_lcd_panel_io_tx_param(io, 0xFF, page4, sizeof(page4));
    if (err == ESP_OK) {
        err = esp_lcd_panel_io_tx_param(io, 0x2D, &all_patterns, 1);
    }
    if (err == ESP_OK) {
        err = esp_lcd_panel_io_tx_param(io, 0x2F, &enable_64_frames, 1);
    }
    if (err == ESP_OK) {
        err = esp_lcd_panel_io_tx_param(io, 0xFF, page0, sizeof(page0));
    }
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "Failed to enable controller BIST: %s", esp_err_to_name(err));
        return err;
    }

    vTaskDelay(pdMS_TO_TICKS(20));
    ESP_LOGI(TAG, "Controller BIST enabled");
    return ESP_OK;
}
